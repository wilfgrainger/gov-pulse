/**
 * Packs the rendered directory site into a single Pages `_worker.js` module.
 *
 * Used where static asset upload is unavailable (it needs a short-lived upload
 * token): the module embeds every page and applies the same `_headers` and
 * `_redirects` rules the static deployment uses, so both paths serve
 * identical bytes and headers.
 */

const TYPES = {
  html: "text/html; charset=utf-8",
  txt: "text/plain; charset=utf-8",
  xml: "application/xml; charset=utf-8",
};

export function parseHeaders(text) {
  const headers = {};
  for (const line of text.split("\n")) {
    const match = /^\s+([^:]+):\s*(.+)$/.exec(line);
    if (match) headers[match[1].trim()] = match[2].trim();
  }
  return headers;
}

export function parseRedirects(text) {
  const redirects = {};
  for (const line of text.split("\n")) {
    const [from, to, status] = line.trim().split(/\s+/);
    if (from && to) redirects[from] = [to, Number(status ?? 302)];
  }
  return redirects;
}

export function renderWorker(files) {
  const pages = {};
  for (const [name, body] of Object.entries(files)) {
    if (name.startsWith("_")) continue;
    pages[`/${name}`] = { body, type: TYPES[name.split(".").pop()] ?? "application/octet-stream" };
  }
  const headers = parseHeaders(files._headers ?? "");
  const redirects = parseRedirects(files._redirects ?? "");
  return `// Generated by directory/worker.mjs. Do not edit.
const PAGES = ${JSON.stringify(pages)};
const HEADERS = ${JSON.stringify(headers)};
const REDIRECTS = ${JSON.stringify(redirects)};

export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== "GET" && request.method !== "HEAD") {
      return new Response("Method not allowed", { status: 405, headers: { ...HEADERS, allow: "GET, HEAD" } });
    }
    const redirect = REDIRECTS[url.pathname];
    if (redirect) return new Response(null, { status: redirect[1], headers: { ...HEADERS, location: redirect[0] } });
    const path = url.pathname === "/" ? "/index.html" : url.pathname;
    const page = PAGES[path];
    const served = page ?? PAGES["/404.html"];
    return new Response(request.method === "HEAD" ? null : served.body, {
      status: page ? 200 : 404,
      headers: { ...HEADERS, "content-type": served.type, "cache-control": "public, max-age=300" },
    });
  },
};
`;
}
